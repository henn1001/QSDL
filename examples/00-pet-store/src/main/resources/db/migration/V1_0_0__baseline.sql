CREATE TABLE IF NOT EXISTS t_category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS t_tag (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS t_pet (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  created_at TIMESTAMP,
  updated_at TIMESTAMP,
  name TEXT NOT NULL,
  status TEXT check (status in ('AVAILABLE', 'PENDING', 'SOLD')),
  category_category_id BIGINT,
  address_street TEXT,
  address_city TEXT,
  address_postal_code TEXT,
  metadata JSONB
);

CREATE TABLE IF NOT EXISTS t_pet_to_t_tag (
  pet_id BIGINT NOT NULL,
  tag_id BIGINT NOT NULL,
  PRIMARY KEY (pet_id, tag_id)
);

CREATE TABLE IF NOT EXISTS t_order_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  quantity INTEGER NOT NULL,
  pet_pet_id BIGINT,
  items_order_id BIGINT
);

CREATE TABLE IF NOT EXISTS t_order (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  created_at TIMESTAMP,
  updated_at TIMESTAMP,
  status TEXT check (status in ('PLACED', 'APPROVED', 'DELIVERED')),
  shipping_address_street TEXT,
  shipping_address_city TEXT,
  shipping_address_postal_code TEXT
);

CREATE TABLE IF NOT EXISTS t_pet_media (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid VARCHAR UNIQUE,
  iv INTEGER,
  creation_date TIMESTAMP NOT NULL,
  modification_date TIMESTAMP,
  pet_id BIGINT NOT NULL,
  media_type TEXT NOT NULL,
  filename TEXT NOT NULL,
  storage_key TEXT NOT NULL
);

ALTER TABLE IF EXISTS t_pet ADD CONSTRAINT fk_t_pet_category FOREIGN KEY (category_category_id) REFERENCES t_category(id);
ALTER TABLE IF EXISTS t_pet_to_t_tag ADD CONSTRAINT fk_t_pet_to_t_tag_pet FOREIGN KEY (pet_id) REFERENCES t_pet(id);
ALTER TABLE IF EXISTS t_pet_to_t_tag ADD CONSTRAINT fk_t_pet_to_t_tag_tag FOREIGN KEY (tag_id) REFERENCES t_tag(id);
ALTER TABLE IF EXISTS t_order_item ADD CONSTRAINT fk_t_order_item_pet FOREIGN KEY (pet_pet_id) REFERENCES t_pet(id);
ALTER TABLE IF EXISTS t_order_item ADD CONSTRAINT fk_t_order_item_items_order FOREIGN KEY (items_order_id) REFERENCES t_order(id);
