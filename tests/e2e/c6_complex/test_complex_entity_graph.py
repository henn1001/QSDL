from pathlib import Path

import pytest

from tests.e2e import assert_mvn, assert_postgres
from tests.e2e.base_e2e_test import BaseE2ETest


class TestE2EComplexEntityGraph(BaseE2ETest):
    """Test E2E for COMPLEX_ENTITY_GRAPH testcase"""

    TESTCASE = """\
      type Customer {
        name: String
        email: String
      }
      type Product {
        name: String
        price: Float
      }
      type OrderItem {
        quantity: Int
        product: Product
      }
      type Order {
        orderNumber: String
        customer: Customer
        items: [OrderItem]! @composition
        relatedProducts: [Product]! @aggregation
      }
    """

    def test_postgres(self, postgres_schema: str) -> None:
        """asserts generated Postgres schema is correct"""
        expected_schema = """\
            CREATE TABLE IF NOT EXISTS t_customer (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              name TEXT,
              email TEXT
            );

            CREATE TABLE IF NOT EXISTS t_product (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              name TEXT,
              price REAL
            );

            CREATE TABLE IF NOT EXISTS t_order_item (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              quantity INTEGER,
              product_product_id BIGINT,
              items_order_id BIGINT
            );

            CREATE TABLE IF NOT EXISTS t_order (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              order_number TEXT,
              customer_customer_id BIGINT
            );

            CREATE TABLE IF NOT EXISTS t_order_to_t_product (
              order_id BIGINT NOT NULL,
              product_id BIGINT NOT NULL,
              PRIMARY KEY (order_id, product_id)
            );

            ALTER TABLE IF EXISTS t_order_item ADD CONSTRAINT fk_t_order_item_product FOREIGN KEY (product_product_id) REFERENCES t_product(id);
            ALTER TABLE IF EXISTS t_order_item ADD CONSTRAINT fk_t_order_item_items_order FOREIGN KEY (items_order_id) REFERENCES t_order(id);
            ALTER TABLE IF EXISTS t_order ADD CONSTRAINT fk_t_order_customer FOREIGN KEY (customer_customer_id) REFERENCES t_customer(id);
            ALTER TABLE IF EXISTS t_order_to_t_product ADD CONSTRAINT fk_t_order_to_t_product_order FOREIGN KEY (order_id) REFERENCES t_order(id);
            ALTER TABLE IF EXISTS t_order_to_t_product ADD CONSTRAINT fk_t_order_to_t_product_product FOREIGN KEY (product_id) REFERENCES t_product(id);
        """

        assert_postgres(postgres_schema, expected_schema)

    def test_openapi(self, openapi_schema: dict) -> None:
        schemas = openapi_schema["components"]["schemas"]

        assert schemas["Order"]["properties"]["customer"] == {"$ref": "#/components/schemas/Customer"}
        assert schemas["OrderItem"]["properties"]["product"] == {"$ref": "#/components/schemas/Product"}
        assert set(schemas["Order"]["properties"]) == {"id", "orderNumber", "customer"}

        products = openapi_schema["paths"]["/orders/{order_id}/products"]
        assert products["get"]["responses"]["200"]["content"]["application/json"]["schema"] == {
            "$ref": "#/components/schemas/ProductList"
        }
        assert (
            openapi_schema["paths"]["/orders/{order_id}/products/{id}/add"]["post"]["responses"]["200"]["description"]
            == "OK"
        )
        assert "/orders/{order_id}/orderitems/{id}" in openapi_schema["paths"]

    def test_spring(self, srcgen: Path) -> None:
        src_root = srcgen / "src" / "main" / "java"

        order_entity = next(src_root.rglob("OrderEntity.java")).read_text(encoding="utf-8")
        assert "private CustomerEntity customer;" in order_entity
        assert '@JoinColumn(name = "customer_customer_id")' in order_entity
        assert "public final Set<OrderItemEntity> orderItems" in order_entity
        assert "public final Set<ProductEntity> products" in order_entity

        item_entity = next(src_root.rglob("OrderItemEntity.java")).read_text(encoding="utf-8")
        assert "private ProductEntity product;" in item_entity
        assert '@JoinColumn(name = "items_order_id")' in item_entity

        product_entity = next(src_root.rglob("ProductEntity.java")).read_text(encoding="utf-8")
        assert '@JoinTable(name = "t_order_to_t_product"' in product_entity
        assert "public final Set<OrderEntity> orders" in product_entity

        order_mapper = next(src_root.rglob("OrderMapper.java")).read_text(encoding="utf-8")
        assert "uses = { CustomerMapper.class }" in order_mapper
        assert '@Mapping(target = "orderItems", ignore = true)' in order_mapper
        assert '@Mapping(target = "products", ignore = true)' in order_mapper

    @pytest.mark.integration
    def test_integration(self, srcgen: Path) -> None:
        """runs mvn clean test to verify generated code compiles and tests pass"""
        assert_mvn(srcgen)
