from pathlib import Path

import pytest

from tests.e2e import assert_mvn, assert_postgres
from tests.e2e.base_e2e_test import BaseE2ETest


class TestE2EOneToOne(BaseE2ETest):
    """Test E2E for ONE_TO_ONE testcase

    one-to-one relations are modelled as unique foreign keys  in the owning entity's table.

    * assert that foreign keys are unique
    * assert that foreign keys are in the owning entity's table
    * assert that we can use the same entity type more than once in a one-to-one relation
    * assert at least two levels of nesting works

    """

    TESTCASE = """\
      type User {
        primary_metric: Metric
        secondary_metric: Metric
      }
      type Metric {
        likes: Int
        role: Role
      }
      type Role {
        name: String
        foobar: Unrelated
      }
      type Unrelated {
        description: String
      }
    """

    def test_postgres(self, postgres_schema: str) -> None:
        """asserts generated Postgres schema is correct"""
        expected_schema = """\
            CREATE TABLE IF NOT EXISTS t_user (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              primary_metric_metric_id BIGINT,
              secondary_metric_metric_id BIGINT
            );

            CREATE TABLE IF NOT EXISTS t_metric (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              likes INTEGER,
              role_role_id BIGINT
            );

            CREATE TABLE IF NOT EXISTS t_role (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              name TEXT,
              foobar_unrelated_id BIGINT
            );

            CREATE TABLE IF NOT EXISTS t_unrelated (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              uid VARCHAR UNIQUE,
              iv INTEGER,
              creation_date TIMESTAMP NOT NULL,
              modification_date TIMESTAMP,
              description TEXT
            );

            ALTER TABLE IF EXISTS t_user ADD CONSTRAINT fk_t_user_primary_metric FOREIGN KEY (primary_metric_metric_id) REFERENCES t_metric(id);
            ALTER TABLE IF EXISTS t_user ADD CONSTRAINT fk_t_user_secondary_metric FOREIGN KEY (secondary_metric_metric_id) REFERENCES t_metric(id);
            ALTER TABLE IF EXISTS t_metric ADD CONSTRAINT fk_t_metric_role FOREIGN KEY (role_role_id) REFERENCES t_role(id);
            ALTER TABLE IF EXISTS t_role ADD CONSTRAINT fk_t_role_foobar FOREIGN KEY (foobar_unrelated_id) REFERENCES t_unrelated(id);
        """

        assert_postgres(postgres_schema, expected_schema)

    def test_openapi(self, openapi_schema: dict) -> None:
        schemas = openapi_schema["components"]["schemas"]

        user = schemas["User"]
        assert user["properties"]["primary_metric"] == {"$ref": "#/components/schemas/Metric"}
        assert user["properties"]["secondary_metric"] == {"$ref": "#/components/schemas/Metric"}
        assert schemas["Metric"]["properties"]["role"] == {"$ref": "#/components/schemas/Role"}

        users = openapi_schema["paths"]["/users"]
        assert users["post"]["requestBody"]["content"]["application/json"]["schema"] == {
            "$ref": "#/components/schemas/User"
        }
        assert users["post"]["responses"]["200"]["content"]["application/json"]["schema"] == {
            "$ref": "#/components/schemas/User"
        }
        assert (
            openapi_schema["paths"]["/users/{id}"]["get"]["responses"]["200"]["content"]["application/json"]["schema"]
            == {"$ref": "#/components/schemas/User"}
        )

    def test_spring(self, srcgen: Path) -> None:
        src_root = srcgen / "src" / "main" / "java"

        user_entity = next(src_root.rglob("UserEntity.java")).read_text(encoding="utf-8")
        assert (
            '@OneToOne(cascade = CascadeType.ALL, orphanRemoval = true)\n    @JoinColumn(name = "primary_metric_metric_id")'
            in user_entity
        )
        assert (
            '@OneToOne(cascade = CascadeType.ALL, orphanRemoval = true)\n    @JoinColumn(name = "secondary_metric_metric_id")'
            in user_entity
        )

        metric_entity = next(src_root.rglob("MetricEntity.java")).read_text(encoding="utf-8")
        assert (
            '@OneToOne(cascade = CascadeType.ALL, orphanRemoval = true)\n    @JoinColumn(name = "role_role_id")'
            in metric_entity
        )
        assert len(list(src_root.rglob("UserRepository.java"))) == 1
        assert len(list(src_root.rglob("UserService.java"))) == 1
        assert len(list(src_root.rglob("UserController.java"))) == 1

    @pytest.mark.integration
    def test_integration(self, srcgen: Path) -> None:
        """runs mvn clean test to verify generated code compiles and tests pass"""
        assert_mvn()
